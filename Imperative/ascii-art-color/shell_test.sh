#!/bin/bash

echo "banana"
go run . --color=red "banana"

echo "Hello World"
go run . --color=red "hello world"

echo "1 + 1 = 2"
go run . --color=green "1 + 1 = 2"

echo "(%&) ??"
go run . --color=yellow "(%&) ??"

echo "Where"
go run . --color=blue r "Where"

echo "(%&) ??"
go run . --color=orange % "(%&) ??"

echo "(%&) ??"
go run . --color=purple ?? "(%&) ??"

echo "HeY GuYs"
go run . --color=orange GuYs "HeY GuYs"

echo 'RGB()'
go run . --color=blue B 'RGB()'

echo "AbBcDe"
go run . --color=green "AbBcDe"

echo "larry 123 frake"
go run . --color=white "larry 123 frake"

echo "$%this 734Dbf, 123 frake!"
go run . --color=cyan "$%this 734Dbf, 123 frake!"

echo "Hello\nThere"
go run . --color=red There "Hello\nThere"

echo "Hello\n\nThere"
go run . --color=yellow "Hello\n\nThere"

echo "{Hello & There #}"
go run . --color=purple "{Hello & There #}"

echo "MaD3IrA&LiSboN"
go run . --color=black LiS "MaD3IrA&LiSboN"

echo ":;<=>?@"
go run . --color=red ":;<=>?@"

echo "\"#$%&'()*+"
go run . --color=cyan '$%&' "\"#$%&'()*+"
echo "GHJ^*&*@#"
go run . --color=yellow "GHJ^*&*@#"

echo "Hello"
go run . --color="rgb(255, 0, 0)" H "Hello"

echo "Hummer"
go run . --color=#ff0000 me "Hummer" 

echo "a king kitten have kit"
go run . --color=red kit "a king kitten have kit"

echo "Racecar in a car race"
go run . --color="hsl(0, 100%, 50%)" car "Racecar in a car race"